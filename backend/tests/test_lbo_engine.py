"""Numerical regression tests; expected results never call production helpers."""

import pytest
from pydantic import ValidationError

from app.financial import (
    FinancialModelError, HistoricalFinancials, OperatingAssumptions,
    TransactionAssumptions, run_lbo_model,
)
from app.financial.models import LBOResult


HISTORICAL = dict(
    revenue=1000, cogs=600, ebitda=300, cash=50, accounts_receivable=100,
    inventory=80, accounts_payable=60, ppe=500, debt=200, shareholders_equity=470,
)
TRANSACTION = dict(
    purchase_multiple_ev_ebitda=10, debt_percentage=0.7, interest_rate=0.08,
    exit_multiple=10,
)
OPERATING = dict(
    revenue_growth_rate=0.05, ebitda_margin=0.3, tax_rate=0.25,
    dso_days=45, dio_days=60, dpo_days=30, capex_pct_of_rev=0.04,
)


def run_case(*, historical=None, transaction=None, operating=None):
    return run_lbo_model(
        HistoricalFinancials(**(HISTORICAL | (historical or {}))),
        TransactionAssumptions(**(TRANSACTION | (transaction or {}))),
        OperatingAssumptions(**(OPERATING | (operating or {}))),
    )


def test_golden_case_year_one_complete():
    result = run_case()
    assert result.historical == HistoricalFinancials(**HISTORICAL)
    assert result.historical_cogs_ratio == pytest.approx(0.6)
    assert result.transaction.purchase_enterprise_value == pytest.approx(3000)
    assert result.transaction.initial_debt == pytest.approx(2100)
    assert result.transaction.initial_equity == pytest.approx(900)

    # Independent Year 1 arithmetic: 315 - 100 - 168 = 47 EBT, 35.25 NI.
    ar = 45 / 365 * 1050
    inventory = 60 / 365 * 630
    ap = 30 / 365 * 630
    nwc = ar + inventory - ap
    cfads = 35.25 + 100 - (nwc - 120) - 42
    optional = cfads - 21
    ending_debt = 2100 - 21 - optional
    expected = dict(
        year=1, beginning_revenue=1000, revenue=1050, cogs=630, ebitda=315,
        accounts_receivable=ar, inventory=inventory, accounts_payable=ap,
        prior_nwc=120, nwc=nwc, change_in_nwc=nwc - 120,
        beginning_ppe=500, capex=42, depreciation=100, ending_ppe=442,
        beginning_debt=2100, interest_expense=168, ebit=215, ebt=47,
        taxes=11.75, net_income=35.25, cfads=cfads,
        mandatory_debt_paydown=21, optional_debt_paydown=optional, ending_debt=ending_debt,
        beginning_cash=50, retained_cash_flow=0, ending_cash=50,
        beginning_equity=470, ending_equity=505.25,
        total_assets=50 + ar + inventory + 442,
        total_liabilities=ap + ending_debt, balance_check=-1900,
    )
    assert result.projected_years[0].model_dump() == pytest.approx(expected, rel=1e-12, abs=1e-10)


def test_golden_case_full_horizon_and_returns():
    result = run_case()
    # Independent 40-digit Decimal ledger, retained as constants; not output
    # generated by the production engine. The derivation is documented in docs.
    expected_debt = [
        2067.9828767123287671, 1975.0609931506849315, 1869.0337537671232877,
        1748.0743350719178082, 1610.3270790589383562,
    ]
    assert [p.ending_debt for p in result.projected_years] == pytest.approx(expected_debt, rel=1e-12)
    assert len(result.projected_years) == 5
    assert [p.year for p in result.projected_years] == [1, 2, 3, 4, 5]
    final = result.projected_years[4]
    assert final.revenue == pytest.approx(1276.2815625, rel=1e-12)
    assert final.ebitda == pytest.approx(382.88446875, rel=1e-12)
    assert final.cfads == pytest.approx(137.7472560129794521, rel=1e-12)
    assert result.returns.exit_enterprise_value == pytest.approx(3828.8446875, rel=1e-12)
    assert result.returns.exit_debt == pytest.approx(1610.3270790589383562, rel=1e-12)
    assert result.returns.exit_equity == pytest.approx(2218.5176084410616438, rel=1e-12)
    assert result.returns.moic == pytest.approx(2.4650195649345129, rel=1e-12)
    assert result.returns.irr == pytest.approx(0.1977441934779717, rel=1e-12)


def test_all_year_formulas_and_roll_forwards():
    result = run_case()
    prior_revenue, prior_ppe, prior_debt = 1000, 500, 2100
    prior_nwc, prior_cash, prior_equity = 120, 50, 470
    for year in result.projected_years:
        assert year.beginning_revenue == pytest.approx(prior_revenue)
        assert year.revenue == pytest.approx(prior_revenue * 1.05)
        assert year.cogs == pytest.approx(year.revenue * 0.6)
        assert year.ebitda == pytest.approx(year.revenue * 0.3)
        assert year.beginning_ppe == pytest.approx(prior_ppe)
        assert year.capex == pytest.approx(year.revenue * 0.04)
        assert year.depreciation == pytest.approx(prior_ppe * 0.2)
        assert year.ending_ppe == pytest.approx(prior_ppe + year.capex - year.depreciation)
        assert year.beginning_debt == pytest.approx(prior_debt)
        assert year.interest_expense == pytest.approx(prior_debt * 0.08)
        assert year.ebit == pytest.approx(year.ebitda - year.depreciation)
        assert year.ebt == pytest.approx(year.ebit - year.interest_expense)
        assert year.taxes == pytest.approx(max(year.ebt, 0) * 0.25)
        assert year.net_income == pytest.approx(year.ebt - year.taxes)
        assert year.accounts_receivable == pytest.approx(year.revenue * 45 / 365)
        assert year.inventory == pytest.approx(year.cogs * 60 / 365)
        assert year.accounts_payable == pytest.approx(year.cogs * 30 / 365)
        assert year.nwc == pytest.approx(year.accounts_receivable + year.inventory - year.accounts_payable)
        assert year.prior_nwc == pytest.approx(prior_nwc)
        assert year.change_in_nwc == pytest.approx(year.nwc - prior_nwc)
        assert year.cfads == pytest.approx(year.net_income + year.depreciation - year.change_in_nwc - year.capex)
        assert year.mandatory_debt_paydown == pytest.approx(21)
        assert year.optional_debt_paydown == pytest.approx(max(year.cfads - 21, 0))
        assert year.ending_debt == pytest.approx(prior_debt - year.mandatory_debt_paydown - year.optional_debt_paydown)
        assert year.ending_debt >= 0
        assert year.retained_cash_flow == pytest.approx(year.cfads - year.mandatory_debt_paydown - year.optional_debt_paydown)
        assert year.beginning_cash == pytest.approx(prior_cash)
        assert year.ending_cash == pytest.approx(prior_cash + year.retained_cash_flow)
        assert year.beginning_equity == pytest.approx(prior_equity)
        assert year.ending_equity == pytest.approx(prior_equity + year.net_income)
        assert year.total_assets == pytest.approx(year.ending_cash + year.accounts_receivable + year.inventory + year.ending_ppe)
        assert year.total_liabilities == pytest.approx(year.accounts_payable + year.ending_debt)
        assert year.balance_check == pytest.approx(year.total_assets - year.total_liabilities - year.ending_equity)
        prior_revenue, prior_ppe, prior_debt = year.revenue, year.ending_ppe, year.ending_debt
        prior_nwc, prior_cash, prior_equity = year.nwc, year.ending_cash, year.ending_equity


def test_historical_debt_is_not_acquisition_debt():
    result = run_case(historical={"debt": 1})
    assert result.historical.debt == 1
    assert result.projected_years[0].beginning_debt == pytest.approx(2100)
    assert result.projected_years == run_case().projected_years


def test_year_two_interest_uses_beginning_not_ending_or_average_debt():
    first, second = run_case().projected_years[:2]
    assert second.interest_expense == pytest.approx(first.ending_debt * 0.08)
    assert second.interest_expense != pytest.approx(second.ending_debt * 0.08)
    assert second.interest_expense != pytest.approx((second.beginning_debt + second.ending_debt) / 2 * 0.08)


def test_negative_cfads_and_cash_are_preserved_without_new_debt():
    result = run_case(operating={"ebitda_margin": 0, "capex_pct_of_rev": 0.5})
    prior_cash = 50
    for year in result.projected_years:
        assert year.ebt < 0
        assert year.taxes == 0
        assert year.cfads < 0
        assert year.optional_debt_paydown == 0
        assert year.ending_debt == pytest.approx(year.beginning_debt - 21)
        assert year.retained_cash_flow == pytest.approx(year.cfads - 21)
        assert year.ending_cash == pytest.approx(prior_cash + year.retained_cash_flow)
        assert year.ending_cash < 0
        prior_cash = year.ending_cash
    assert [d.year for d in result.diagnostics if d.code == "negative_cash"] == [1, 2, 3, 4, 5]
    assert result.returns.exit_equity < 0
    assert result.returns.moic < 0
    assert result.returns.irr is None


def test_full_debt_repayment_retains_excess_and_future_interest_is_zero():
    result = run_case(transaction={"debt_percentage": 0.01})
    first = result.projected_years[0]
    assert first.beginning_debt == pytest.approx(30)
    assert first.mandatory_debt_paydown == pytest.approx(0.3)
    assert first.optional_debt_paydown == pytest.approx(29.7)
    assert first.ending_debt == 0
    assert first.retained_cash_flow == pytest.approx(first.cfads - 30)
    assert first.retained_cash_flow > 0
    for year in result.projected_years[1:]:
        assert year.beginning_debt == year.ending_debt == 0
        assert year.interest_expense == 0
        assert year.mandatory_debt_paydown == year.optional_debt_paydown == 0
        assert year.retained_cash_flow == pytest.approx(year.cfads)
    assert result.returns.exit_equity == pytest.approx(result.returns.exit_enterprise_value)


def test_unlevered_acquisition_and_zero_exit_equity():
    result = run_case(transaction={"debt_percentage": 0}, operating={"ebitda_margin": 0})
    assert result.transaction.initial_equity == pytest.approx(3000)
    assert all(p.beginning_debt == p.ending_debt == p.interest_expense == 0 for p in result.projected_years)
    assert result.returns.exit_equity == result.returns.moic == 0
    assert result.returns.irr is None
    assert any(d.code == "non_computable_irr" for d in result.diagnostics)


def test_balance_sheet_is_diagnostic_and_not_plugged():
    result = run_case()
    for year in result.projected_years:
        assert year.ending_cash == pytest.approx(50)
        assert year.balance_check == pytest.approx(-1900)
    assert [d.year for d in result.diagnostics if d.code == "simplified_balance_sheet_imbalance"] == [1, 2, 3, 4, 5]
    # Historical accounting balances. If acquisition debt equals historical debt,
    # the indicative roll-forward stays balanced, without a warning or cash plug.
    balanced = run_case(transaction={"debt_percentage": 200 / 3000})
    assert all(p.balance_check == pytest.approx(0, abs=1e-9) for p in balanced.projected_years)
    assert not any(d.code == "simplified_balance_sheet_imbalance" for d in balanced.diagnostics)


def test_cash_does_not_enter_exit_equity():
    ordinary, cash_rich = run_case(), run_case(historical={"cash": 10000})
    assert ordinary.returns == cash_rich.returns


def test_deterministic_immutable_and_no_input_mutation():
    inputs = (HistoricalFinancials(**HISTORICAL), TransactionAssumptions(**TRANSACTION), OperatingAssumptions(**OPERATING))
    before = [value.model_dump() for value in inputs]
    first = run_lbo_model(*inputs)
    assert first == run_lbo_model(*inputs)
    assert before == [value.model_dump() for value in inputs]
    with pytest.raises(ValidationError):
        inputs[0].revenue = 2
    with pytest.raises(ValidationError):
        first.projected_years[0].revenue = 2
    assert LBOResult.model_validate_json(first.model_dump_json()) == first



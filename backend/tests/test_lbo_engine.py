def test_legitimate_boundary_and_large_assumptions_are_allowed():
    result = run_case(
        historical={"cash": -10, "shareholders_equity": -100},
        transaction={"interest_rate": 0, "debt_percentage": 0},
        operating={"revenue_growth_rate": 2, "ebitda_margin": 1, "tax_rate": 1,
                   "dso_days": 500, "dio_days": 0, "dpo_days": 700, "capex_pct_of_rev": 2},
    )
    assert result.projected_years[0].revenue == pytest.approx(3000)
    assert result.projected_years[0].beginning_equity == -100
    assert result.projected_years[0].beginning_cash == -10
    decline = run_case(operating={"revenue_growth_rate": -0.9, "tax_rate": 0})
    assert decline.projected_years[0].revenue == pytest.approx(100)
    assert all(p.taxes == 0 for p in decline.projected_years)


